const support = { reportedTimeBasis: 'beijing_standard', overseasDeclared: false };
const input: BirthInputV2 = {
  schemaVersion: 'birth-input-v2', birthDate: '2025-02-03', calendarType: 'solar', isLeapMonth: false,
  timezone: 'Asia/Shanghai', timeBasis: 'standard_clock', reportedPrecision: 'exact', birthTime: '22:10', timeRange: null,
};
const unknown = (birthDate = input.birthDate): BirthInputV2 => ({ ...input, birthDate, birthTime: null, reportedPrecision: 'unknown' });
const range = (birthDate: string, start: string, end: string, endDayOffset: 0 | 1 = 0): BirthInputV2 => ({ ...input, birthDate, birthTime: null, reportedPrecision: 'range', timeRange: { start, end, endDayOffset } });
function complete(value: BirthInputV2): CompleteChartVariants {
  const result = enumerateChartVariants(value, support);
  expect(result.status).toBe('complete');
  if (result.status !== 'complete') throw new Error(result.status);
  return result;
}
function reseal(snapshot: BaziSignalSnapshot) {
  snapshot.meta.artifactHash = semanticHash(snapshot);
  return BaziSignalSnapshotSchema.safeParse(snapshot);
}
// Public identifiers can be regenerated by any caller; they are not proof of coverage.
function reindex(result: CompleteChartVariants) {
  for (const s of result.segments) s.segmentId = stableId('chart-segment', {
    start: s.start, end: s.end, startInclusive: s.startInclusive, endInclusive: s.endInclusive, variantId: s.variantId,
  });
  for (const v of result.variants) v.segmentIds = result.segments.filter(s => s.variantId === v.variantId).map(s => s.segmentId);
  return result;
}
afterEach(() => vi.restoreAllMocks());

describe('historical standard-clock scope regression', () => {
  const edges = [
    '1900-01-01', '1900-12-31', '1901-01-01', '1919-04-12', '1919-04-13', '1919-09-30', '1919-10-01',
    '1949-05-27', '1949-05-28', '1949-12-31', '1950-01-01', '1985-12-31', '1986-01-01', '1991-12-31', '1992-01-01',
  ];
  it.each(edges)('does not block verified fixed UTC+08 fields merely because of date %s', birthDate => {
    expect(prepareBirthInput({ ...input, birthDate }, support).status).toBe('supported');
    expect(prepareBirthInput(unknown(birthDate), support).status).toBe('supported');
    expect(prepareBirthInput(unknown(birthDate), { ...support, reportedTimeBasis: 'historical_unverified' }).status).toBe('unavailable');
  });
  // Literal transition dates independently expanded from IANA PRC rules, not a production helper.
  it.each([
    ['1986-05-04', '1986-09-14'], ['1987-04-12', '1987-09-13'], ['1988-04-17', '1988-09-11'],
    ['1989-04-16', '1989-09-17'], ['1990-04-15', '1990-09-16'], ['1991-04-14', '1991-09-15'],
  ])('keeps standard fields distinct from unverified civil records around %s / %s', (start, end) => {
    for (const date of [start, end]) {
      const [y, m, d] = date.split('-').map(Number);
      for (const offset of [-1, 0, 1]) {
        const birthDate = Solar.fromYmd(y, m, d).nextDay(offset).toYmd();
        for (const value of [unknown(birthDate), range(birthDate, '01:59', '03:01'), range(birthDate, '23:59', '00:00', 1),
          ...['00:00', '01:00', '01:59', '02:00', '02:59', '03:00'].map(birthTime => ({ ...input, birthDate, birthTime }))]) {
          expect(prepareBirthInput(value, support).status).toBe('supported');
          expect(prepareBirthInput(value, { ...support, reportedTimeBasis: 'historical_unverified' })).toMatchObject({ status: 'unavailable', input: null, timeConfidence: null });
        }
      }
    }
  });
  it('does not perform an implicit DST shift on fixed-standard summer dates', () => {
    const value = { ...input, birthDate: '1987-08-03', birthTime: '00:30' };
    const result = complete(value);
    expect(result.coverage.start).toBe('1987-08-03T00:30:00+08:00');
    expect(result.variants[0].chart.hourBranch).toBe('子');
    expect(complete({ ...value, calendarType: 'lunar' }).coverage.start).toBe('1987-09-25T00:30:00+08:00');
    expect(complete({ ...value, calendarType: 'lunar', birthDate: '1987-06-01', isLeapMonth: true }).coverage.start).toBe('1987-07-26T00:30:00+08:00');
  });
  it('rejects an unavailable historical assessment contradicting an explicit standard declaration', () => {
    expect(BirthSupportAssessmentSchema.safeParse({ ...support, status: 'unavailable', reasonCode: 'historical_time_basis_unverified' }).success).toBe(false);
  });
});

describe('partial chart consumer contract', () => {
  function partial() {
    const snapshot = syntheticBazi({ stableThemes: ['analysis_research'] }).snapshot;
    snapshot.timeConfidence = 'unknown';
    snapshot.status = 'partial';
    snapshot.chartVariants[0].knownPillars = ['year', 'month', 'day'];
    return snapshot;
  }
  it('permits stable non-hour signals only within an explicitly partial unknown snapshot', () => {
    expect(reseal(partial()).success).toBe(true);
    const forged = partial();
    forged.status = 'available';
    expect(reseal(forged).success).toBe(false);
  });
  it('rejects unknown variants that silently omit the day pillar', () => {
    const forged = partial();
    forged.chartVariants[0].knownPillars = ['year', 'month'];
    expect(reseal(forged).success).toBe(false);
  });
  it('rejects known-time variants that silently omit the hour pillar', () => {
    const forged = syntheticBazi({ stableThemes: ['analysis_research'] }).snapshot;
    forged.chartVariants[0].knownPillars = ['year', 'month', 'day'];
    expect(reseal(forged).success).toBe(false);
  });
});

describe('serialized complete coverage is semantically verified', () => {
  it('rejects an internally consistent morning-only unknown result', () => {
    const forged = complete(unknown('2000-06-15'));
    forged.segments = forged.segments.slice(0, 4);
    forged.coverage.end = forged.segments.at(-1)!.end;
    expect(ChartVariantEnumerationSchema.safeParse(reindex(forged)).success).toBe(false);
  });
  it('rejects a range mislabeled exact and a cross-shichen range mislabeled same-shichen', () => {
    const forged = complete(range('2000-06-15', '14:50', '15:10'));
    forged.timeConfidence = 'exact';
    expect(ChartVariantEnumerationSchema.safeParse(forged).success).toBe(false);
    forged.timeConfidence = 'approximate_same_shichen';
    expect(ChartVariantEnumerationSchema.safeParse(forged).success).toBe(false);
  });
  it('rejects a rehashed segment merging both sides of 立春 into the first chart', () => {
    const forged = complete(range('2025-02-03', '22:10', '22:11'));
    forged.variants = [forged.variants[0]];
    forged.segments = [forged.segments[0]];
    forged.segments[0].end = forged.coverage.end;
    forged.segments[0].endInclusive = true;
    forged.stablePillars = { ...forged.variants[0].chart.pillars };
    expect(ChartVariantEnumerationSchema.safeParse(reindex(forged)).success).toBe(false);
  });
  it('rejects correct hash and references attached to the wrong civil date', () => {
    const forged = complete({ ...input, birthDate: '2000-06-15' });
    for (const s of forged.segments) {
      s.start = s.start.replace('2000-06-15', '2000-06-16');
      s.end = s.end.replace('2000-06-15', '2000-06-16');
      s.calculationPoint = s.start;
    }
    forged.coverage.start = forged.segments[0].start;
    forged.coverage.end = forged.segments[0].end;
    expect(ChartVariantEnumerationSchema.safeParse(reindex(forged)).success).toBe(false);
  });
});

