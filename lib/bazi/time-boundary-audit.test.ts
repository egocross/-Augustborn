describe('short solar term segments, dedupe and lunar equivalence', () => {
  it('retains a one-second pre-term segment and a closed term endpoint', () => {
    // Instrument only term placement; use real calendar facts on either side of 2025 立春.
    const original = calendar.canonicalChartAt;
    vi.spyOn(calendar, 'solarTermOffsets').mockReturnValue([22 * 3600 + 10 * 60 + 1]);
    vi.spyOn(calendar, 'canonicalChartAt').mockImplementation((base, seconds, known) => original(base, seconds + 27, known));
    const result = complete(range('2025-02-03', '22:10', '22:11'));
    expect(result.segments[0].end).toBe('2025-02-03T22:10:01+08:00');
    expect(result.variants).toHaveLength(2);
    vi.spyOn(calendar, 'solarTermOffsets').mockReturnValue([22 * 3600 + 11 * 60]);
    vi.spyOn(calendar, 'canonicalChartAt').mockImplementation((base, seconds, known) => original(base, seconds - 32, known));
    const endpoint = complete(range('2025-02-03', '22:10', '22:11'));
    expect(endpoint.variants).toHaveLength(2);
    expect(endpoint.segments.at(-1)).toMatchObject({ start: '2025-02-03T22:11:00+08:00', end: '2025-02-03T22:11:00+08:00', endInclusive: true });
  });
  it('applies the cap after dedupe even with over 32 distinct segments', () => {
    vi.spyOn(calendar, 'solarTermOffsets').mockReturnValue(Array.from({ length: 40 }, (_, i) => i + 1));
    const result = complete(unknown('2000-06-15'));
    expect(result.segments.length).toBeGreaterThan(32);
    expect(result.variants).toHaveLength(1);
    expect(result.variants[0].segmentIds).toHaveLength(result.segments.length);
  });
  it.each(['exact', 'range', 'unknown'] as const)('preserves leap-month solar-term semantics for %s', precision => {
    // 2023 leap lunar February 15 == April 5, 清明 falls within this day.
    const solar = precision === 'unknown' ? unknown('2023-04-05')
      : precision === 'range' ? range('2023-04-05', '00:00', '23:59') : { ...input, birthDate: '2023-04-05', birthTime: '12:00' };
    const lunar = { ...solar, calendarType: 'lunar' as const, birthDate: '2023-02-15', isLeapMonth: true };
    expect(complete(lunar)).toEqual(complete(solar));
    if (precision !== 'exact') expect(complete(lunar).stablePillars.month).toBeNull();
  });
});


describe('calendar extremes and independently asserted term-side states', () => {
  it.each([1900, 1901, 1919, 1949, 1950, 1986, 1991, 2100])('covers all twelve month-switching days in standard-clock year %i', year => {
    const table = Solar.fromYmd(year, 6, 15).getLunar().getJieQiTable();
    const terms = LunarUtil.JIE_QI_IN_USE.filter((_, i) => i % 2 === 0).map(key => table[key]).filter(term => term.getYear() === year);
    expect(terms).toHaveLength(12);
    for (const term of terms) {
      const result = complete(unknown(term.toYmd()));
      expect(result.variants).toHaveLength(2);
      expect(result.stablePillars.month).toBeNull();
      expect(result.variants.every(v => v.chart.pillars.hour === null)).toBe(true);
    }
  });
  it('switches at the exact library term second, with no one-second gap', () => {
    const base = Solar.fromYmd(2025, 2, 3);
    const result = complete(range('2025-02-03', '22:10', '22:11'));
    for (const [second, year, month] of [[79827, '甲辰', '丁丑'], [79828, '乙巳', '戊寅'], [79829, '乙巳', '戊寅']] as const) {
      const stamp = calendar.standardClockTimestamp(base, second);
      const segments = result.segments.filter(s => stamp >= s.start && (stamp < s.end || (stamp === s.end && s.endInclusive)));
      expect(segments).toHaveLength(1);
      const chart = result.variants.find(v => v.variantId === segments[0].variantId)!.chart;
      expect(chart.pillars).toMatchObject({ year, month });
      expect(calendar.canonicalChartAt(base, second, true).pillars).toMatchObject({ year, month });
    }
  });
  it('retains the pre-noon term state instead of taking the noon chart as all-day stability', () => {
    // 2023 立春 is in the morning; complements the 2025 late-evening regression.
    const result = complete(unknown('2023-02-04'));
    expect(result.variants.map(v => v.chart.pillars.year)).toEqual(['壬寅', '癸卯']);
    expect(result.variants.map(v => v.chart.pillars.month)).toEqual(['癸丑', '甲寅']);
    expect(result.stablePillars.year).toBeNull();
    expect(result.stablePillars.month).toBeNull();
    expect(result.stablePillars.hour).toBeNull();
  });
});
