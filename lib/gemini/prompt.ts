import type { BaziChart } from '@/lib/bazi/types';

/** Creates the complete, serializable prompt passed to the report model. */
export const createReportPrompt = (chart: BaziChart): string => `
人生是一系列决策，需要在正确的地方选择正确的行业，从事什么工作、与谁一起共事都
非常重要。请结合下方出生数据，为我生成一份现代自我探索报告，帮我了解自己的性格倾向、
优势特征、工作方式与环境偏好。

下方数据只供你在内部推理使用。不要在正文里引用它的字段名、原始值，也不要写出其中的
任何传统术语或符号。

写作风格：像一位冷静、务实的自我探索顾问当面给建议，直接、具体、说人话。不要写成
公文或评估报告；章节标题要用直白、口语的说法，可以用问句；避免「锚定」「取向」
「匹配」「高阶推演」「本报告基于……」这类措辞。

分析的硬性要求：

1. 不要迎合我。不要恭维、不要用讨好的语气，也不要用平衡话术把负面结论说成优点。
   如果结构显示明显的短板、失衡或需要回避的方向，直接指出，并说明它在现实中可能
   以什么方式表现出来、需要额外注意什么。
2. 不看过往记录。除下方出生数据外，没有任何背景信息，不要假设我的经历、行业、
   年龄阶段或处境，也不要引用任何历史对话或未提供的事实。性格倾向只能写成倾向，
   不能当成既定事实。
3. 客观分析。每条判断都要给出我能自己验证的观察线索（在什么情境下、我通常会怎么
   反应），不要只给抽象形容词；数据里无法得出的问题就直接说明无法判断，不要编造。
4. 全文禁止出现任何传统命理或玄学措辞与符号，包括但不限于：四柱、日主、月令、天干、
   地支、干支、五行、生克、冲合刑害、身强身弱、用神、十神、生肖、属相、农历、节气、
   吉凶、命理、算命、八字。不要罗列出生数据的原始字段，也不要写出任何干支字符。
   所有结论都用性格、优势、工作方式、环境偏好这类现代语言表达。
5. 如果数据里 timeKnown 为 false（我不知道准确出生时间）：不要给出任何依赖出生时辰的
   判断，也不要猜测时辰，用一句话说明这一限制即可。
6. 如果数据里带有出生地区：它只作为环境背景使用，不得据此推断我现在住在哪里，也不得
   断言某个城市或地区的好坏。

每条重要判断按「结论 → 判断依据 → 现实表现 → 适用边界」展开：

- 「结论」先给一句明确判断。
- 「判断依据」写成我能自己核对的观察线索（在什么情境下、我通常怎么反应），不要引用
  任何术语、字段名或原始数据。
- 「现实表现」要落到选工作、进组织、找搭档或做取舍时可观察的现象。
- 「适用边界」要说明这是倾向性描述，哪些事仅凭出生信息无法判断。

请按下列叙事顺序组织报告，但不要把章节数量写死。可根据这份数据的信息量合并或拆分
相邻内容，不得改变总体顺序，也不要为了凑章节而重复结论。章节标题原样使用下面每段
开头标注的标题（包括括号里的补充），不要改写、不要省略括号内容：

1. 核心性格与底层矛盾。先用两三句话概括我的整体能量结构与行事风格，再提炼一个最值得
   关注的底层矛盾：它如何反复出现在我的日常和工作里。不要同时罗列多个互不相关的「核心」。
2. 在什么地方？（方位与环境）。说明更适合我的环境气质、城市节奏、平台类型与组织文化，
   以及应该回避的环境特征。不要谈方向、方位，也不要判断某个地理位置的好坏。
3. 从事什么行业？（方向选择）。先说适合创造什么价值、承担什么工作内容，再列举可选行业
   标签与应谨慎的方向；要说明具体工作形态、价值链位置、选择标准和回避条件。
4. 怎么工作？与谁共事？说明更匹配的组织形态、团队角色、自主权与协作方式；再说合作伙伴
   应补足什么能力、哪些组合容易摩擦。不得给未知的具体他人贴性格标签。
5. 给你的客观建议。收束全文，只抓一个当前最值得防范的决策陷阱和一条优先路径。给出明确
   的取舍原则、可执行的专注方向以及 2–4 个自查问题，不要用空泛的鼓励作结尾。

措辞保持克制：用「倾向」「可能」「通常」这类非确定的表达，不做绝对断言，不承诺
成功或结果，不使用吉凶恐吓。不提供医疗、心理健康、法律、财务或投资方面的具体
建议；涉及重大人生决策时，提醒我自行判断。结尾必须包含一段清楚的免责声明。

所有文本使用简体中文，包括章节标题、正文、要点和免责声明。只返回符合要求的 JSON。

出生数据：
${JSON.stringify(chart)}
`.trim();
