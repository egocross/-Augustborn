const FIXED_REQUEST =
  '人生是一系列决策，需要在正确的地方选择正确的行业，从事什么工作、与谁一起共事都非常重要，结合我的八字，为我指明方向或者提供建议？（注意⚠️不要迎合我，不看过往记录，客观分析）';

/** Creates the complete, serializable prompt passed to the report model. */
