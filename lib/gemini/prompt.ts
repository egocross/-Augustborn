import type { BaziChart } from '@/lib/bazi/types';

/** Creates the complete, serializable prompt passed to the report model. */
export const createReportPrompt = (chart: BaziChart): string => `
人生是一系列决策，需要在正确的地方选择正确的行业，从事什么工作、与谁一起共事都
非常重要。请结合下方排盘数据（出生年月时换算所得，是本次分析唯一的变量），为我
指明方向或者提供建议。这是一份用于帮助决策的高级分析报告，不是传统断语的堆砌。

分析的硬性要求：

1. 不要迎合我。不要恭维、不要用讨好的语气，也不要用平衡话术把负面结论说成优点。
   如果结构显示明显的短板、失衡或需要回避的方向，直接指出，并说明它在现实中可能
   以什么方式表现出来、需要额外注意什么。
2. 不看过往记录。除下方排盘数据外，没有任何背景信息，不要假设我的经历、性格、
   行业、年龄阶段或处境，也不要引用任何历史对话或未提供的事实。
3. 客观分析。每一条判断都要给出它在四柱、时支或五行统计上的依据；数据里没有的
   信息不要编造，无法从排盘得出的问题就直接说明无法判断。区分「排盘事实」与
   「命理体系内的推演」；后者不得写成已被现实验证的客观因果。

内容的论证格式：

- 重要判断尽量按「结论 → 盘面依据 → 现实表现 → 适用边界」展开。
- 「盘面依据」要点明日主、月令、具体干支关系或五行数量，不要只给结论。
- 「现实表现」要翻译成选工作、进组织、找搭档或做取舍时可观察的现象，不停留在术语。
- 「适用边界」要说明这是倾向性推演，哪些事仅凭排盘无法判断。

请按下列叙事顺序组织报告，但不要把章节数量写死。可根据这份排盘的信息量合并或拆分
相邻内容，不得改变总体顺序，也不要为了凑章节而重复结论：

1. 盘面总纲与核心矛盾。开头先列出四柱，交代日主、月令、强弱判断及其依据，再从最明显的
   五行失衡、生克、冲合刑害或其他结构中，提炼一个最值得关注的底层矛盾。不要同时罗列多个
   互不相关的「核心」。
2. 环境与方位。先把所需五行翻译为更适合的环境、城市气质、平台节奏与组织文化，再视情况给出
   传统方位参考。如果谈东西南北，必须说明它来自五行方位映射，不得断言某个真实城市必然有利，
   也不得在没有出生地数据时断言「不适合在出生地发展」。
3. 行业与工作内容。从盘面的能量转换逻辑出发，先说适合创造什么价值、承担什么工作内容，再列举
   可选行业标签与应谨慎的方向。不要只罗列「属木」「属火」行业；要说明具体工作形态、价值链位置、
   选择标准和回避条件。
4. 工作方式与共事对象。说明更匹配的组织形态、团队角色、自主权与协作方式；再说合作伙伴应补足
   什么能力、哪些组合容易摩擦。不得根据五行给未知的具体他人贴性格标签。
5. 最后的客观建议。收束全文，只抓一个当前最值得防范的决策陷阱和一条优先路径。给出明确的取舍原则、
   可执行的专注方向以及 2–4 个自查问题，不要用空泛的鼓励作结尾。

措辞保持克制：用「倾向」「可能」「通常」这类非确定的表达，不做绝对断言，不承诺
成功或结果，不使用吉凶恐吓。不提供医疗、心理健康、法律、财务或投资方面的具体
建议；涉及重大人生决策时，提醒我自行判断。结尾必须包含一段清楚的免责声明。

所有文本使用简体中文，包括标题、摘要、章节标题、正文、要点和免责声明，并保留
日主、天干、地支、五行等中文术语。只返回符合要求的 JSON。

排盘数据：
${JSON.stringify(chart)}
`.trim();
